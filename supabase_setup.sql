-- Run this once in Supabase Dashboard -> SQL Editor -> New query.
create table if not exists public.ontin8_results (
    id bigint generated by default as identity primary key,
    timestamp_vietnam text not null,
    attempt_id text not null,
    student_name text not null,
    class_name text not null,
    mcq_correct integer not null,
    mcq_total integer not null,
    written_correct integer not null,
    written_total integer not null,
    total_correct integer not null,
    total_questions integer not null,
    percent numeric not null,
    mcq_answers_json text,
    written_answers_json text,
    review_flags text
);

-- Keep Row Level Security enabled. The app writes server-side using a secret key
-- stored only in Streamlit Cloud Secrets; never expose that key to students.
alter table public.ontin8_results enable row level security;
